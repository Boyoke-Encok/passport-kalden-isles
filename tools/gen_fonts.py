#!/usr/bin/env python3
"""Build-time font rasterizer for the stdlib-only passport renderer.

Renders the glyphs the passport needs from the system DejaVu /
Liberation TTFs with Pillow (LOCAL ONLY -- the shipped main.py never
touches a font file or Pillow) and emits a compact binary blob:
for every font spec, for every char in CHARSET, one record:
  adv, w, h, xoff+128, yoff+128, then w*h grayscale bytes.
The blob is zlib-compressed and base64-encoded so it can live as a
single string constant inside main.py.
"""
import base64
import json
import sys
import zlib

from PIL import Image, ImageDraw, ImageFont

DEJAVU = "/usr/share/fonts/truetype/dejavu"
LIBER = "/usr/share/fonts/truetype/liberation"

# font key -> (path, size). Keys must match FONT_SPECS in main.py.
SPECS = {
    "serif_b19": (f"{DEJAVU}/DejaVuSerif-Bold.ttf", 19),
    "serif_b15": (f"{DEJAVU}/DejaVuSerif-Bold.ttf", 15),
    "sans_b13": (f"{DEJAVU}/DejaVuSans-Bold.ttf", 13),
    "sans_r11": (f"{DEJAVU}/DejaVuSans.ttf", 11),
    "sans_b17": (f"{DEJAVU}/DejaVuSans-Bold.ttf", 17),
    "sans_b15": (f"{DEJAVU}/DejaVuSans-Bold.ttf", 15),
    "sans_r9": (f"{DEJAVU}/DejaVuSans.ttf", 9),
    "sans_r8": (f"{DEJAVU}/DejaVuSans.ttf", 8),
    "sans_b10": (f"{DEJAVU}/DejaVuSans-Bold.ttf", 10),
    "mono17": (f"{DEJAVU}/DejaVuSansMono.ttf", 17),
    "serif_i25": (f"{LIBER}/LiberationSerif-Italic.ttf", 25),
}

# Every character the passport text uses: printable ASCII, Latin-1
# supplement (accented Kalden/Icelandic letters, middle dot) and the
# two dashes. Sorted by code point so the runtime can index by order.
CHARSET = "".join(
    [chr(c) for c in range(0x20, 0x7F)]
    + [chr(c) for c in range(0xA0, 0x100)]
    + ["\u2013", "\u2014"]
)


def rasterize(path, size):
    font = ImageFont.truetype(path, size)
    out = bytearray()
    for ch in CHARSET:
        adv = int(round(font.getlength(ch) * 4))  # quarter-pixel advance
        x0, y0, x1, y1 = font.getbbox(ch)
        w, h = x1 - x0, y1 - y0
        if w <= 0 or h <= 0:
            out += bytes([adv, 0, 0, 128, 128])
            continue
        img = Image.new("L", (w, h), 0)
        d = ImageDraw.Draw(img)
        d.text((-x0, -y0), ch, font=font, fill=255)
        out += bytes([adv & 0xFF, w, h, (x0 + 128) & 0xFF, (y0 + 128) & 0xFF])
        out += img.tobytes()
    return bytes(out)


def main():
    blob = bytearray()
    index = {}
    for key, (path, size) in SPECS.items():
        data = rasterize(path, size)
        index[key] = (len(blob), len(data))
        blob += data
    raw = bytes(blob)
    comp = zlib.compress(raw, 9)
    b64 = base64.b64encode(comp).decode()
    print(f"fonts: {len(SPECS)} specs, {len(CHARSET)} chars each", file=sys.stderr)
    print(f"raw {len(raw)} bytes -> zlib {len(comp)} -> b64 {len(b64)} chars", file=sys.stderr)
    with open(sys.argv[1], "w") as f:
        f.write("# generated by tools/gen_fonts.py -- do not edit by hand\n")
        f.write(f"CHARSET = {CHARSET!r}\n")
        f.write(f"FONT_INDEX = {json.dumps(index)}\n")
        f.write(f"FONT_BLOB_B64 = (\n")
        for i in range(0, len(b64), 100):
            f.write(f"    {b64[i:i+100]!r}\n")
        f.write(")\n")
    print("wrote", sys.argv[1], file=sys.stderr)


if __name__ == "__main__":
    main()
